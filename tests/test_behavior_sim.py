# -- the safety layer beneath everything -------------------------------------------


def test_the_monitor_chickens_through_the_engine(monkeypatch):
    world = cold_plains_scenario()
    run = build_sim(world, monkeypatch=monkeypatch)
    # Walk the run into the field, then drop below the 35% threshold.
    for _ in range(10):
        run.engine.tick()
        world.advance_tick(0.5)
    world.hp = 200  # 20% of max
    with pytest.raises(ChickenExit):
        for _ in range(5):
            run.engine.tick()
            world.advance_tick(0.5)


def test_a_stalled_run_idle_bails(monkeypatch):
    # A contrived stall: out of town, a monster that cannot be reached and
    # never dies, with walking disabled. Nothing to send, no progress.
    world = ColdPlains()
    world.area = offsets.AREA_COLD_PLAINS
    world.position = ARRIVAL
    world.belt = []
    # The NON-patrol run on purpose: with a patrol the bot has somewhere
    # to be and keeps making progress, which is the patrol working rather
    # than the watchdog failing. This test is about the watchdog, so it
    # needs a run that genuinely runs out of things to do.
    run = build_sim(
        world,
        monkeypatch=monkeypatch,
        idle_bail_s=5.0,
        run_file="cold-plains-stage-b.toml",
    )
    # Skip the town/waypoint steps so the stall happens in the field.
    run.engine._index = 2
    world.monsters = [SimMonster(99, (1200, 1200))]  # outside engage radius
    world.armor_ratio = 1.0
    with pytest.raises(IdleBail):
        for _ in range(60):
            run.engine.tick()
            world.advance_tick(0.5)


def test_idle_bail_does_not_fire_while_the_bot_is_working(sim):
    run, world = sim
    assert run_to_completion(run, world)  # no IdleBail escaped


