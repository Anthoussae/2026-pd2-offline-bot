def test_attacks_stand_still_and_pickups_do_not(sim):
    run, world = sim
    run_to_completion(run, world)
    modifiers = {}
    for (_, button, stand_still) in run.gated.clicks:
        modifiers.setdefault(button, set()).add(stand_still)
    # Left-clicks come in two flavours and the difference is load-bearing:
    # an attack holds SHIFT, a pickup must not.
    attacks = [e for e in run.trace if isinstance(e.action, AttackUnit)]
    pickups = [e for e in run.trace if isinstance(e.action, PickUpItem)]
    assert attacks and pickups
    assert modifiers["left"] == {True, False}
    assert modifiers["right"] == {False}  # casts are never shifted


