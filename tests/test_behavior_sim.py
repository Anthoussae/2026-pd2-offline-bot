def test_the_pickit_decided_correctly(sim):
    run, world = sim
    run_to_completion(run, world)
    picked = {
        e.action.unit_id: e.action.position
        for e in run.trace if isinstance(e.action, PickUpItem)
    }
    # 501 healing potion -> belt; 503 rare -> keep; 504 unique -> attempted
    # and refused; 502 magic -> never touched, no rule matches it.
    assert 501 in picked and 503 in picked and 504 in picked
    assert 502 not in picked
    assert HEAL_KIND in [kind for kind, _ in world.belt]
    assert 999 in world.inventory


def test_the_stuck_item_was_bounded_and_flagged(sim):
    run, world = sim
    run_to_completion(run, world)
    attempts = [
        e for e in run.trace
        if isinstance(e.action, PickUpItem) and e.action.unit_id == 504
    ]
    # Two bounded rounds, not an endless loop: one full click schedule
    # before the cleanse, and — because the cleanse freed space — one
    # more after, sharing one memory across both pickup steps.
    services = run.engine._states[2].services
    assert len(attempts) == 2 * services.pickup_click_attempts
    # And the conclusion was recorded where the rest of the game can see it.
    assert services.inventory_full
    assert 504 in services.stuck


